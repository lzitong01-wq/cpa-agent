def render(template: str, **kwargs) -> str:
    """安全渲染：缺失的占位符填空字符串，避免 KeyError 打断对话。"""
    class _Safe(dict):
        def __missing__(self, key):  # noqa: D105
            return ""

    return template.format_map(_Safe(**kwargs))




